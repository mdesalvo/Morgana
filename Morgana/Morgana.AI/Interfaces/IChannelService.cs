using Morgana.Contracts;

namespace Morgana.AI.Interfaces;

/// <summary>
/// Abstraction over the outbound channel that delivers Morgana's responses to an end user.
/// A channel is the transport + client pair (e.g. SignalR + Cauldron web UI, HTTP webhook,
/// polling REST endpoint, ...) through which messages leave the actor system and reach
/// whoever is consuming them.
/// </summary>
/// <remarks>
/// <para><strong>Purpose:</strong></para>
/// <para>This service decouples the actor system from any specific transport. Actors invoke
/// it to emit messages without knowing whether the underlying channel is SignalR, a webhook,
/// Server-Sent Events, or a plain HTTP long-poll.</para>
///
/// <para><strong>Metadata contract:</strong></para>
/// <para>This interface intentionally exposes no channel identity or capability budget:
/// identity + capabilities belong to the <em>client</em> that announces itself at the
/// conversation-start handshake, not to the transport that carries the bytes. Per-conversation
/// metadata is published by <c>ConversationManagerActor</c> into the <c>IChannelMetadataStore</c>;
/// everything downstream (adapter, supervisor, presenter) consults the store keyed by
/// conversation id. A missing entry is always an error — there is no transport-level fallback.</para>
/// </remarks>
public interface IChannelService
{
    /// <summary>
    /// Sends a message to the conversation group targeted by
    /// <see cref="ChannelMessage.ConversationId"/>. The message envelope carries the
    /// full payload (text, message type, quick replies, rich card, agent identity, error
    /// reason, fading duration) and is delivered through the channel's native transport.
    /// </summary>
    /// <param name="channelMessage">The fully-formed channel message to deliver.</param>
    /// <returns>Task representing the async send operation</returns>
    Task SendMessageAsync(ChannelMessage channelMessage);

    /// <summary>
    /// Sends a streaming chunk to a conversation group via the channel for progressive response rendering.
    /// Enables real-time display of agent responses as they are generated by the LLM. Callers are
    /// responsible for gating the call on the conversation's registered capabilities; transports
    /// that cannot carry streaming are free to no-op.
    /// </summary>
    /// <param name="conversationId">Unique identifier of the conversation (channel group/routing key)</param>
    /// <param name="chunkText">Partial response text to append to the current message</param>
    /// <returns>Task representing the async send operation</returns>
    Task SendStreamChunkAsync(string conversationId, string chunkText);
}

/// <summary>
/// Factory that resolves the concrete <see cref="IChannelService"/> implementation for a given
/// <c>deliveryMode</c> declared by the channel at the conversation-start handshake.
/// </summary>
/// <remarks>
/// <para><strong>Why a factory:</strong></para>
/// <para>Morgana serves multiple channel profiles (SignalR for rich UIs, HTTP webhook for
/// plain-text clients, …). Each profile maps to a concrete <see cref="IChannelService"/>.
/// Instead of hard-coding the mapping in a switch or tying dispatch to the free-form
/// <see cref="ChannelCoordinates.ChannelName"/> (client-controlled, potentially infinite),
/// the factory receives every transport at DI registration keyed on its <c>deliveryMode</c>
/// and resolves the right one per-conversation via
/// <see cref="ChannelCoordinates.DeliveryMode"/>.</para>
///
/// <para><strong>Finite-by-registration:</strong></para>
/// <para>The set of valid <c>deliveryMode</c> keys is defined by what's registered in DI — not
/// by an enum in the codebase. Adding a new transport means adding one registration; no contract
/// file needs to move.</para>
///
/// <para><strong>Fail-loud:</strong></para>
/// <para><see cref="Resolve"/> throws <see cref="InvalidOperationException"/> if the key is not
/// registered. The start-conversation gate should consult <see cref="IsRegistered"/> first and
/// reject unknown keys with a 400 — reaching <see cref="Resolve"/> with an unregistered key at
/// send-time is an internal invariant violation.</para>
/// </remarks>
public interface IChannelServiceFactory
{
    /// <summary>
    /// Resolves the <see cref="IChannelService"/> registered under <paramref name="deliveryMode"/>.
    /// The key is normalised (trimmed + lowercased) before lookup, matching the normalisation
    /// applied by <c>ConversationManagerActor</c> at handshake ingress.
    /// </summary>
    /// <param name="deliveryMode">The delivery-mode key declared by the channel.</param>
    /// <returns>The concrete <see cref="IChannelService"/> registered for this mode.</returns>
    /// <exception cref="InvalidOperationException">No implementation registered for this key.</exception>
    IChannelService Resolve(string deliveryMode);

    /// <summary>
    /// Returns <see langword="true"/> if a concrete <see cref="IChannelService"/> is registered
    /// for <paramref name="deliveryMode"/>. Used by the start-conversation gate to reject
    /// unknown delivery modes at the handshake with a 400 instead of letting the failure surface
    /// at send-time.
    /// </summary>
    /// <param name="deliveryMode">The delivery-mode key to check.</param>
    bool IsRegistered(string deliveryMode);
}
